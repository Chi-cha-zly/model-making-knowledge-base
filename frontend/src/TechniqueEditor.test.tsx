import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import userEvent from '@testing-library/user-event'
import TechniqueEditor from './TechniqueEditor'
beforeEach(()=>{const m=new Map<string,string>();vi.stubGlobal('localStorage',{getItem:(k:string)=>m.get(k)||null,setItem:(k:string,v:string)=>m.set(k,v),removeItem:(k:string)=>m.delete(k)})})
afterEach(()=>{cleanup();vi.unstubAllGlobals()})
it('converts legacy steps without losing text and previews them',()=>{
 render(<TechniqueEditor technique={{id:1,title:'旧文',category:'素组',steps:['第一段','第二段'],tags:[],source_ids:[],status:'withdrawn'}} sources={[]} onSave={vi.fn()} onClose={vi.fn()} />)
 expect(screen.getByDisplayValue('第一段')).toBeInTheDocument()
 fireEvent.click(screen.getByRole('button',{name:'预览'}))
 expect(screen.getByText('第二段')).toBeInTheDocument()
})
it('protects dirty close and keeps a local recovery draft',async()=>{
 const close=vi.fn()
 render(<TechniqueEditor sources={[]} onSave={vi.fn()} onClose={close} />)
 fireEvent.change(screen.getByLabelText('标题'),{target:{value:'草稿'}})
 await waitFor(()=>expect(window.localStorage.getItem('modelkb.technique-draft.v1.new')).toContain('草稿'))
 fireEvent.click(screen.getByRole('button',{name:'关闭编辑器'}))
 expect(close).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('button',{name:'保留草稿并关闭'}))
 expect(close).toHaveBeenCalled()
})
it('keeps image order on delayed upload and disables mutation until it finishes',async()=>{
 let resolve!:(v:Response)=>void
 vi.stubGlobal('fetch',vi.fn(()=>new Promise<Response>(r=>{resolve=r})))
 const save=vi.fn()
 render(<TechniqueEditor technique={{id:1,title:'旧文',category:'素组',steps:['第一段','第二段'],tags:[],source_ids:[1],status:'published'}} sources={[{id:1,title:'资料'}]} onSave={save} onClose={vi.fn()}/>)
 fireEvent.focus(screen.getByDisplayValue('第一段'))
 fireEvent.change(screen.getByLabelText('插入图片'),{target:{files:[new File(['png'],'a.png',{type:'image/png'})]}})
 expect(screen.getByDisplayValue('第一段')).toBeDisabled()
 expect(screen.getByRole('button',{name:'保存技巧'})).toBeDisabled()
 resolve(new Response(JSON.stringify({id:9,filename:'a.png'}),{status:201}))
 await waitFor(()=>expect(screen.getByRole('img')).toHaveAttribute('src','/api/v1/attachments/9'))
 fireEvent.click(screen.getByRole('button',{name:'保存技巧'}))
 await waitFor(()=>expect(save).toHaveBeenCalled())
 expect(save.mock.calls[0][0].content_blocks).toEqual([{type:'paragraph',text:'第一段'},{type:'image',attachment_id:9,caption:''},{type:'paragraph',text:'第二段'}])
})
it('keeps content after failed upload and permits a retry',async()=>{
 vi.stubGlobal('fetch',vi.fn(()=>Promise.resolve(new Response(JSON.stringify({detail:'网络不可用'}),{status:500}))))
 render(<TechniqueEditor sources={[]} onSave={vi.fn()} onClose={vi.fn()}/>)
 fireEvent.change(screen.getByLabelText('正文'),{target:{value:'保留正文'}})
 fireEvent.change(screen.getByLabelText('插入图片'),{target:{files:[new File(['png'],'a.png',{type:'image/png'})]}})
 expect(await screen.findByRole('alert')).toHaveTextContent('网络不可用')
 expect(screen.getByDisplayValue('保留正文')).not.toBeDisabled()
})
it('locks fields during deferred save and clears draft only after success',async()=>{
 let resolve!:()=>void
 const save=vi.fn(()=>new Promise<void>(r=>{resolve=r}))
 render(<TechniqueEditor sources={[]} onSave={save} onClose={vi.fn()}/>)
 fireEvent.change(screen.getByLabelText('标题'),{target:{value:'待保存'}})
 await waitFor(()=>expect(window.localStorage.getItem('modelkb.technique-draft.v1.new')).toContain('待保存'))
 fireEvent.click(screen.getByRole('button',{name:'保存技巧'}))
 expect(screen.getByLabelText('标题')).toBeDisabled()
 expect(window.localStorage.getItem('modelkb.technique-draft.v1.new')).not.toBeNull()
 resolve()
 await waitFor(()=>expect(window.localStorage.getItem('modelkb.technique-draft.v1.new')).toBeNull())
})
it('keeps editor open if retaining a draft fails',()=>{
 const close=vi.fn()
 vi.spyOn(window.localStorage,'setItem').mockImplementation(()=>{throw Error('quota')})
 render(<TechniqueEditor sources={[]} onSave={vi.fn()} onClose={close}/>)
 fireEvent.change(screen.getByLabelText('标题'),{target:{value:'不可丢失'}})
 fireEvent.click(screen.getByRole('button',{name:'关闭编辑器'}))
 fireEvent.click(screen.getByRole('button',{name:'保留草稿并关闭'}))
 expect(close).not.toHaveBeenCalled()
 expect(screen.getByDisplayValue('不可丢失')).toBeInTheDocument()
})
it('requires an explicit recovery choice and warns about changed server content',()=>{
 window.localStorage.setItem('modelkb.technique-draft.v1.new',JSON.stringify({version:1,base:'older',values:{title:'恢复标题',category:'素组',summary:'',tags:'',sourceIds:[],original:true,status:'published',content_blocks:[{type:'paragraph',text:'恢复正文'}],attachment_ids:[]}}))
 render(<TechniqueEditor sources={[]} onSave={vi.fn()} onClose={vi.fn()}/>)
 expect(screen.getByLabelText('标题')).toBeDisabled()
 expect(screen.getByText(/服务器内容已变更/)).toBeInTheDocument()
 fireEvent.click(screen.getByRole('button',{name:'恢复草稿'}))
 expect(screen.getByDisplayValue('恢复正文')).toBeInTheDocument()
 expect(screen.getByLabelText('标题')).not.toBeDisabled()
})
it('traps keyboard focus inside discard confirmation',async()=>{
 const user=userEvent.setup()
 render(<TechniqueEditor sources={[]} onSave={vi.fn()} onClose={vi.fn()}/>)
 fireEvent.change(screen.getByLabelText('标题'),{target:{value:'有修改'}})
 fireEvent.click(screen.getByRole('button',{name:'关闭编辑器'}))
 const last=screen.getByRole('button',{name:'丢弃修改'}),first=screen.getByRole('button',{name:'继续写作'})
 last.focus();await user.tab();expect(first).toHaveFocus()
 await user.tab({shift:true});expect(last).toHaveFocus()
 await user.click(first)
 await waitFor(()=>expect(screen.getByLabelText('标题')).toHaveFocus())
})
it('reorders content and renders escaped text through the shared preview',()=>{
 render(<TechniqueEditor technique={{id:1,title:'旧文',category:'素组',steps:['第一段','<script>第二段</script>'],tags:[],source_ids:[1],status:'published'}} sources={[{id:1,title:'资料'}]} onSave={vi.fn()} onClose={vi.fn()}/>)
 fireEvent.click(screen.getByRole('button',{name:'上移内容 2'}))
 fireEvent.click(screen.getByRole('button',{name:'预览'}))
 const p=document.querySelectorAll('.article-body p')
 expect(p[0]).toHaveTextContent('<script>第二段</script>')
 expect(p[1]).toHaveTextContent('第一段')
 expect(document.querySelector('.article-body script')).toBeNull()
})
